def migrate():
    moved = 0
    skipped = 0
    for csv_rel, exp, label, manifest_extra in MIGRATIONS:
        src = RESULTS / csv_rel
        if not src.exists():
            print(f"  skip (not found): {csv_rel}")
            skipped += 1
            continue

        dest_dir = RESULTS / exp / "runs" / label
        dest_data = dest_dir / "data.csv"
        if dest_data.exists():
            print(f"  skip (already migrated): {dest_data}")
            skipped += 1
            continue

        dest_dir.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, dest_data)

        manifest = {
            "experiment":      exp,
            "label":           label,
            "started_utc":     "pre-refactor (estimated)",
            "ended_utc":       "pre-refactor (estimated)",
            "migrated_from":   str(src.relative_to(ROOT)),
            "migrated_at_utc": __import__("datetime").datetime.utcnow().isoformat() + "Z",
            **manifest_extra,
        }
        (dest_dir / "manifest.json").write_text(
            json.dumps(manifest, indent=2, sort_keys=False))
        print(f"  moved {csv_rel} -> {dest_data.relative_to(ROOT)}")
        moved += 1

    print(f"\nmigrated {moved}, skipped {skipped}")
    return moved


if __name__ == "__main__":
    n = migrate()
    if n > 0:
        print("\nNext: verify with `python3 scripts/aggregate.py e3_compute --list`")
        print("If happy, the original flat .csv files can be removed manually.")
